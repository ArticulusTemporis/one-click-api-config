// Bake the publisher certificate into the bundle so the single exe can install
// its own trust root on first run (no separate .cer file next to it).
//
// Run before bundling: node scripts/embed-cert.js

import fs from 'node:fs';
import path from 'node:path';

const cer = path.join(process.cwd(), 'dist', 'aac-codesign.cer');
const out = path.join(process.cwd(), 'src', 'core', 'cert.js');

if (!fs.existsSync(cer)) {
  console.log('no certificate yet - writing an empty stub');
  fs.writeFileSync(out, 'export const CERT_BASE64 = \'\';\nexport const CERT_NAME = \'Example Company Config\';\n', 'utf8');
  process.exit(0);
}

const b64 = fs.readFileSync(cer).toString('base64');
const body = [
  '// generated by scripts/embed-cert.js - do not edit',
  `export const CERT_BASE64 = '${b64}';`,
  "export const CERT_NAME = 'Example Company Config';",
  '',
].join('\n');

fs.writeFileSync(out, body, 'utf8');
console.log('embedded certificate:', (b64.length / 1024).toFixed(1), 'KB base64');
